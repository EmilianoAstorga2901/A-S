export function newsForAsset(assetId, items = referenceNews) {
  return items.filter((item) => item.affectedAssetIds?.includes(assetId));
}

export function normalizeLiveNews(item, assetIdBySymbol = {}) {
  const symbol = String(item.symbol || '').toUpperCase();
  return {
    id: `live-${item.id || item.datetime || symbol}-${item.headline || 'news'}`,
    headline: item.headline || 'Actualización de mercado',
    summary: item.summary || '',
    url: item.url || null,
    imageUrl: item.image || item.imageUrl || '/news/market-context.svg',
    imageAlt: `Imagen relacionada con ${item.headline || symbol || 'el mercado'}`,
    affectedAssetIds: assetIdBySymbol[symbol] ? [assetIdBySymbol[symbol]] : [],
    affectedSymbols: symbol ? [symbol] : [],
    affectedPortfolioIds: [],
    impact: 'uncertain',
    impactLabel: 'Impacto por interpretar',
    relevance: 'La fuente confirma el hecho; Prisma todavía no asignó una dirección de impacto.',
    source: { name: item.source || 'Proveedor conectado', kind: 'live' },
    publishedLabel: item.publishedLabel || item.datetimeLabel || 'Fecha provista por la fuente',
    factStatus: 'Fuente conectada',
  };
}
